// Minimal .xlsx writer with no dependencies.
//
// An .xlsx file is a ZIP archive of XML parts (Office Open XML). This builds
// the handful of parts Excel / Google Sheets / Numbers need, with inline
// strings, a bold frozen header row, autofilter, currency and date formats,
// and stores them in an uncompressed ("stored") ZIP.

const enc = new TextEncoder();

// ---------- ZIP (store method) ----------

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

export function crc32(bytes) {
  let c = 0xffffffff;
  for (let i = 0; i < bytes.length; i++) c = CRC_TABLE[(c ^ bytes[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

/** @param {Array<{name: string, data: Uint8Array}>} files */
export function zipStore(files, date = new Date()) {
  const dosTime = (date.getHours() << 11) | (date.getMinutes() << 5) | (date.getSeconds() >> 1);
  const dosDate = ((date.getFullYear() - 1980) << 9) | ((date.getMonth() + 1) << 5) | date.getDate();
  const chunks = [];
  const central = [];
  let offset = 0;

  for (const f of files) {
    const name = enc.encode(f.name);
    const crc = crc32(f.data);
    const local = new DataView(new ArrayBuffer(30));
    local.setUint32(0, 0x04034b50, true);
    local.setUint16(4, 20, true); // version needed
    local.setUint16(6, 0x0800, true); // UTF-8 names
    local.setUint16(8, 0, true); // stored
    local.setUint16(10, dosTime, true);
    local.setUint16(12, dosDate, true);
    local.setUint32(14, crc, true);
    local.setUint32(18, f.data.length, true);
    local.setUint32(22, f.data.length, true);
    local.setUint16(26, name.length, true);
    local.setUint16(28, 0, true);
    chunks.push(new Uint8Array(local.buffer), name, f.data);

    const cd = new DataView(new ArrayBuffer(46));
    cd.setUint32(0, 0x02014b50, true);
    cd.setUint16(4, 20, true);
    cd.setUint16(6, 20, true);
    cd.setUint16(8, 0x0800, true);
    cd.setUint16(10, 0, true);
    cd.setUint16(12, dosTime, true);
    cd.setUint16(14, dosDate, true);
    cd.setUint32(16, crc, true);
    cd.setUint32(20, f.data.length, true);
    cd.setUint32(24, f.data.length, true);
    cd.setUint16(28, name.length, true);
    cd.setUint32(42, offset, true);
    central.push(new Uint8Array(cd.buffer), name);
    offset += 30 + name.length + f.data.length;
  }

  const cdSize = central.reduce((s, c) => s + c.length, 0);
  const end = new DataView(new ArrayBuffer(22));
  end.setUint32(0, 0x06054b50, true);
  end.setUint16(8, files.length, true);
  end.setUint16(10, files.length, true);
  end.setUint32(12, cdSize, true);
  end.setUint32(16, offset, true);

  const all = [...chunks, ...central, new Uint8Array(end.buffer)];
  const out = new Uint8Array(all.reduce((s, c) => s + c.length, 0));
  let p = 0;
  for (const c of all) { out.set(c, p); p += c.length; }
  return out;
}

// ---------- Spreadsheet XML ----------

const xmlEscape = (s) => String(s)
  // Strip characters that are illegal in XML 1.0.
  .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function colName(i) {
  let s = '';
  for (i++; i > 0; i = Math.floor((i - 1) / 26)) s = String.fromCharCode(65 + ((i - 1) % 26)) + s;
  return s;
}

// Style indexes defined in STYLES below.
const STYLE = { text: 0, header: 1, currency: 2, date: 3, percent: 4, int: 5 };

/** "YYYY-MM-DD" -> Excel serial day number (days since 1899-12-30). */
function excelDate(iso) {
  const [y, m, d] = iso.split('-').map(Number);
  return (Date.UTC(y, m - 1, d) - Date.UTC(1899, 11, 30)) / 86400000;
}

/**
 * @typedef {{header: string, type?: 'text'|'currency'|'date'|'percent'|'int', width?: number}} Column
 * @param {{name: string, columns: Column[], rows: any[][]}} sheet
 *   currency values are passed in dollars, dates as "YYYY-MM-DD".
 */
function sheetXml({ columns, rows }) {
  const cell = (value, col, r, c) => {
    const ref = `${colName(c)}${r}`;
    if (value == null || value === '') return '';
    const type = col.type || 'text';
    if (type === 'text' || typeof value !== 'number' && type !== 'date') {
      return `<c r="${ref}" t="inlineStr" s="${STYLE.text}"><is><t xml:space="preserve">${xmlEscape(value)}</t></is></c>`;
    }
    const v = type === 'date' ? excelDate(value) : value;
    return `<c r="${ref}" s="${STYLE[type]}"><v>${v}</v></c>`;
  };

  const headerRow = `<row r="1">${columns.map((col, c) =>
    `<c r="${colName(c)}1" t="inlineStr" s="${STYLE.header}"><is><t>${xmlEscape(col.header)}</t></is></c>`).join('')}</row>`;
  const body = rows.map((row, i) =>
    `<row r="${i + 2}">${row.map((v, c) => cell(v, columns[c], i + 2, c)).join('')}</row>`).join('');
  const cols = columns.map((col, c) => `<col min="${c + 1}" max="${c + 1}" width="${col.width || 14}" customWidth="1"/>`).join('');
  const lastRef = `${colName(columns.length - 1)}${rows.length + 1}`;

  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>
<cols>${cols}</cols>
<sheetData>${headerRow}${body}</sheetData>
${rows.length ? `<autoFilter ref="A1:${lastRef}"/>` : ''}
</worksheet>`;
}

